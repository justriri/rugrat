// Bundles the WebView scenes (webview/src/*.ts + three.js) into single offline HTML documents and
// writes each as a TS module the app can hand to <WebView source={{ html }} />.
//   main.ts -> src/webview/gameHtml.ts   (the replay game)
//   menu.ts -> src/webview/menuHtml.ts   (home and world selection)
import { build } from 'esbuild';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');

async function bundle({ entry, htmlFile, tsFile, constName, extraStyle, extraBody }) {
  const result = await build({
    entryPoints: [resolve(root, entry)],
    bundle: true,
    minify: true,
    format: 'iife',
    target: 'es2019',
    write: false,
    legalComments: 'none',
  });
  const js = result.outputFiles[0].text.replace(/<\/script/gi, '<\/script');
  const html = `<!doctype html>
<html>
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1, maximum-scale=1, user-scalable=no" />
<style>
  html, body { margin: 0; padding: 0; height: 100%; overflow: hidden; background: #8fd6ff; }
${extraStyle}
  canvas { display: block; width: 100%; height: 100%; touch-action: none; -webkit-user-select: none; user-select: none; }
</style>
</head>
<body>
<canvas id="c"></canvas>
${extraBody}
<script>${js}</script>
</body>
</html>`;
  mkdirSync(resolve(root, 'webview/dist'), { recursive: true });
  mkdirSync(resolve(root, dirname(tsFile)), { recursive: true }); // src/webview does not exist in a fresh clone
  writeFileSync(resolve(root, 'webview/dist', htmlFile), html);
  writeFileSync(resolve(root, tsFile), `// GENERATED by webview/build.mjs. Do not edit; run \`npm run build:webview\`.\nexport const ${constName} = ${JSON.stringify(html)};\n`);
  console.log(`${htmlFile} built: ${(html.length / 1024).toFixed(0)} KB`);
}

await bundle({
  entry: 'webview/src/main.ts',
  htmlFile: 'game.html',
  tsFile: 'src/webview/gameHtml.ts',
  constName: 'GAME_HTML',
  extraStyle: '  #flash { position: fixed; left: 0; top: 0; right: 0; bottom: 0; pointer-events: none; opacity: 0; background: #fff; }',
  extraBody: '<div id="flash"></div>',
});
await bundle({ entry: 'webview/src/menu.ts', htmlFile: 'menu.html', tsFile: 'src/webview/menuHtml.ts', constName: 'MENU_HTML', extraStyle: '', extraBody: '' });
